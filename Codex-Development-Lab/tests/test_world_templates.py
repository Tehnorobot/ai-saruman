PROFILE = {"minecraft_version": "1.21.11", "world_profile": "flat-survival-v1",
           "bootstrap_revision": "bootstrap-test-1", "allow_commands": True}


def saved_world(path, *, embedded_player=True, version="1.21.11"):
    """A structural fixture only; it was not generated by a game process."""
    path = Path(path)
    path.mkdir(parents=True, exist_ok=True)
    data = {"DataVersion": (3, 4671), "Version": (10, {"Name": (8, version)}),
            "allowCommands": (1, 0), "LevelName": (8, "Lab template"),
            "WorldGenSettings": (10, {"seed": (4, 0), "generate_features": (1, 0)})}
    if embedded_player:
        data["Player"] = (10, {"UUID": (11, struct.pack(">iiii", 1, 2, 3, 4)),
                               "Inventory": (9, (10, [{"id": (8, "minecraft:diamond")}]))})
    nbt = b"\x0a\x00\x00" + worlds._NBT.encode(10, {"Data": (10, data)})
    (path / "level.dat").write_bytes(gzip.compress(nbt, mtime=0))
    (path / "region").mkdir(exist_ok=True)
    payload = zlib.compress(b"\x0a\x00\x00" + worlds._NBT.encode(10, {
        "DataVersion": (3, 4671), "xPos": (3, 0), "zPos": (3, 0), "Status": (8, "minecraft:full")}))
    raw = bytearray(3 * 4096)
    raw[:4] = (2 << 8 | 1).to_bytes(4, "big")
    raw[8192:8196] = (len(payload) + 1).to_bytes(4, "big")
    raw[8196] = 2
    raw[8197:8197 + len(payload)] = payload
    (path / "region/r.0.0.mca").write_bytes(raw)


def level_data(path):
    parser = worlds._NBT(gzip.decompress(Path(path).read_bytes()))
    assert parser.number("B") == 10
    parser.string()
    return parser.payload(10)["Data"][1]


class WorldProfileTests(unittest.TestCase):
    def test_profile_identity_includes_generation_and_compatibility_inputs(self):
        original = worlds.profile_key(PROFILE)
        for key in ["minecraft_version", "world_profile", "bootstrap_revision",
                    "worldgen_fingerprint", "dependency_fingerprint", "allow_commands", "display_name"]:
            value = deepcopy(PROFILE)
            value[key] = False if key == "allow_commands" else "different"
            with self.subTest(key=key):
                self.assertNotEqual(original, worlds.profile_key(value))

    def test_key_is_stable_for_dictionary_order_and_explicit_defaults(self):
        a = dict(reversed(list(PROFILE.items())))
        a.update(worldgen_fingerprint="vanilla", dependency_fingerprint="vanilla")
        self.assertEqual(worlds.profile_key(a), worlds.profile_key(PROFILE))
        self.assertRegex(worlds.profile_key(a), r"^[a-f0-9]{64}$")

    def test_invalid_profiles_are_rejected(self):
        for value in [None, {}, {**PROFILE, "allow_commands": "true"},
                      {**PROFILE, "display_name": ""}, {**PROFILE, "display_name": "x" * 81},
                      {**PROFILE, "display_name": "Lab\nFixture"}, {**PROFILE, "display_name": {}},
                      {**PROFILE, "extra": float("nan")}, {**PROFILE, "extra": object()},
                      {**PROFILE, "extra": "x" * 65536}]:
            with self.subTest(value_type=type(value).__name__), self.assertRaises(worlds.WorldTemplateError):
                worlds.profile_key(value)


@unittest.skipUnless(sys.platform.startswith("linux") and hasattr(os, "O_NOFOLLOW"),
                     "Verifier template storage uses Linux descriptor/no-replace operations")
class WorldTemplateStorageTests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        self.store = worlds.TemplateStore(self.root / "templates-private")
        self.runs = self.root / "runs"
        self.runs.mkdir()
        self.calls = 0

    def generate(self, path):
        self.calls += 1
        saved_world(path)

    def ensure(self):
        return self.store.ensure(PROFILE, self.generate)

    def test_publish_reuse_and_private_permissions(self):
        first = self.ensure()
        second = self.ensure()
        self.assertFalse(first["reused"])
        self.assertTrue(second["reused"])
        self.assertEqual(first["manifest_sha256"], second["manifest_sha256"])
        self.assertEqual(self.calls, 1)
        self.assertEqual(stat.S_IMODE(self.store.root.stat().st_mode), 0o700)
        for file in Path(first["path"]).rglob("*"):
            self.assertEqual(stat.S_IMODE(file.stat().st_mode), 0o700 if file.is_dir() else 0o600)
            self.assertEqual(file.stat().st_uid, os.geteuid())
        self.assertNotIn("PASS", first["provenance"])

    def test_two_run_worlds_are_independent_and_cannot_contaminate_template(self):
        template = self.ensure()
        a = self.store.clone(PROFILE, self.runs / "job-a")
        b = self.store.clone(PROFILE, self.runs / "job-b")
        files = [Path(x["path"]) / "region/r.0.0.mca" for x in (template, a, b)]
        self.assertEqual(len({p.stat().st_ino for p in files}), 3)
        pristine = files[0].read_bytes()
        files[1].write_bytes(b"changed by a tested mod")
        self.assertEqual(files[0].read_bytes(), pristine)
        self.assertEqual(files[2].read_bytes(), pristine)
        self.assertTrue(self.ensure()["reused"])

    def test_player_files_connections_configs_and_embedded_inventory_are_not_published(self):
        def prepare(path):
            saved_world(path)
            for relative in ["playerdata/a.dat", "advancements/a.json", "stats/a.json",
                             "config/auth.json", "servers.dat", "options.txt", "session.lock",
                             "level.dat_old", "data/.credentials", "data/session.lock"]:
                p = path / relative
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_text("private input")
        result = self.store.ensure(PROFILE, prepare)
        world = Path(result["path"])
        self.assertEqual({p.relative_to(world).as_posix() for p in world.rglob("*") if p.is_file()},
                         {"level.dat", "region/r.0.0.mca"})
        self.assertNotIn("Player", level_data(world / "level.dat"))
        self.assertEqual(level_data(world / "level.dat")["allowCommands"], (1, 1))

    def test_command_permissions_are_profile_scoped_not_leaked_between_jobs(self):
        enabled = self.ensure()
        denied_profile = {**PROFILE, "allow_commands": False}
        denied = self.store.ensure(denied_profile, self.generate)
        self.assertNotEqual(enabled["key"], denied["key"])
        self.assertEqual(level_data(Path(denied["path"]) / "level.dat")["allowCommands"], (1, 0))

    def test_display_name_is_sanitized_for_template_and_clone_and_checked_on_validation(self):
        profile = {**PROFILE, "display_name": "Lab Fixture"}
        result = self.store.ensure(profile, self.generate)
        self.assertNotEqual(result["key"], worlds.profile_key(PROFILE))
        template = Path(result["path"]) / "level.dat"
        self.assertEqual(level_data(template)["LevelName"], (8, "Lab Fixture"))
        clone = self.store.clone(profile, self.runs / "display")
        self.assertEqual(level_data(Path(clone["path"]) / "level.dat")["LevelName"], (8, "Lab Fixture"))
        data = level_data(template)
        data["LevelName"] = (8, "/world-templates/staging/old/generated")
        raw = gzip.compress(b"\x0a\x00\x00" + worlds._NBT.encode(10, {"Data": (10, data)}), mtime=0)
        with self.assertRaisesRegex(worlds.WorldTemplateError, "display name"):
            worlds._level(raw, profile, self.store.limits)

    def test_content_mutation_is_quarantined_and_regenerated(self):
        old = self.ensure()
        (Path(old["path"]) / "region/r.0.0.mca").write_bytes(b"broken")
        new = self.ensure()
        self.assertFalse(new["reused"])
        self.assertEqual(self.calls, 2)
        self.assertEqual(len(list((self.store.root / "quarantine").iterdir())), 1)
        self.store.clone(PROFILE, self.runs / "fresh")

    def test_new_private_or_unknown_file_in_cache_is_not_silently_reused(self):
        old = self.ensure()
        (Path(old["path"]) / "session.lock").write_bytes(b"untrusted")
        self.assertFalse(self.ensure()["reused"])
        self.assertEqual(self.calls, 2)

    def test_manifest_tampering_is_rejected_and_reprepared(self):
        for raw in ["{broken", "[]", "null"]:
            result = self.ensure()
            manifest = Path(result["path"]).parent / "manifest.json"
            manifest.write_text(raw, encoding="utf-8")
            self.assertFalse(self.ensure()["reused"])

    def test_clone_refuses_mutated_cache_until_ensure_repairs_it(self):
        result = self.ensure()
        (Path(result["path"]) / "data").mkdir()
        (Path(result["path"]) / "data/new.dat").write_bytes(b"modified")
        with self.assertRaises(worlds.WorldTemplateError):
            self.store.clone(PROFILE, self.runs / "bad")
        self.assertFalse((self.runs / "bad").exists())

    def test_prepare_exception_and_interrupt_do_not_publish_partial_worlds(self):
        for exception in [RuntimeError("generation failed"), KeyboardInterrupt()]:
            def prepare(path):
                (path / "level.dat").write_bytes(b"partial")
                raise exception
            with self.subTest(type=type(exception).__name__), self.assertRaises(type(exception)):
                self.store.ensure(PROFILE, prepare)
            self.assertEqual(list((self.store.root / "templates").iterdir()), [])
            self.assertEqual(list((self.store.root / "staging").iterdir()), [])
        self.ensure()

    def test_staging_from_killed_generator_is_cleaned_only_for_its_locked_key(self):
        key = worlds.profile_key(PROFILE)
        staging = self.store.root / "staging"
        old = staging / (key + "-" + "a" * 32)
        old.mkdir()
        external = self.root / "keep"
        external.write_text("keep")
        (old / "link").symlink_to(external)
        unrelated = staging / ("f" * 64 + "-" + "a" * 32)
        unrelated.mkdir()
        self.ensure()
        self.assertFalse(old.exists())
        self.assertTrue(unrelated.exists())
        self.assertEqual(external.read_text(), "keep")

    def test_empty_or_wrong_version_world_cannot_be_published(self):
        for prepare in [lambda path: None, lambda path: saved_world(path, version="1.20.1")]:
            with self.assertRaises(worlds.WorldTemplateError):
                self.store.ensure(PROFILE, prepare)
            self.assertEqual(list((self.store.root / "templates").iterdir()), [])

    def test_region_header_only_and_out_of_bounds_allocations_are_rejected(self):
        for raw in [bytes(8192), b"truncated", (0xFFFFFF01).to_bytes(4, "big") + bytes(12284)]:
            def prepare(path):
                saved_world(path)
                (path / "region/r.0.0.mca").write_bytes(raw)
            with self.subTest(length=len(raw)), self.assertRaises(worlds.WorldTemplateError):
                self.store.ensure(PROFILE, prepare)

    def test_symlink_and_hardlink_sources_cannot_escape(self):
        external = self.root / "external.txt"
        external.write_text("keep")
        for mode in ["symlink", "hardlink"]:
            def prepare(path):
                saved_world(path)
                (path / "data").mkdir()
                link = path / "data/outside.dat"
                link.symlink_to(external) if mode == "symlink" else os.link(external, link)
            with self.subTest(mode=mode), self.assertRaises(worlds.WorldTemplateError):
                self.store.ensure(PROFILE, prepare)
            self.assertEqual(external.read_text(), "keep")
            self.assertEqual(list((self.store.root / "staging").iterdir()), [])

    def test_cleanup_after_failure_unlinks_symlink_without_touching_external_directory(self):
        external = self.root / "external"
        external.mkdir()
        (external / "keep.txt").write_text("keep")
        def prepare(path):
            (path / "data").symlink_to(external, target_is_directory=True)
            raise RuntimeError("cancelled")
        with self.assertRaises(RuntimeError):
            self.store.ensure(PROFILE, prepare)
        self.assertEqual((external / "keep.txt").read_text(), "keep")

    def test_existing_run_even_empty_is_never_replaced(self):
        self.ensure()
        dest = self.runs / "existing"
        dest.mkdir()
        inode = dest.stat().st_ino
        with self.assertRaises(FileExistsError):
            self.store.clone(PROFILE, dest)
        self.assertEqual(dest.stat().st_ino, inode)
        self.assertEqual(list(dest.iterdir()), [])

    def test_atomic_publication_refuses_racing_destination(self):
        self.ensure()
        dest = self.runs / "raced"
        publish = worlds._publish_noreplace
        def race(*args):
            dest.mkdir()
            return publish(*args)
        with patch.object(worlds, "_publish_noreplace", side_effect=race), self.assertRaises(FileExistsError):
            self.store.clone(PROFILE, dest)
        self.assertEqual(list(dest.iterdir()), [])
        self.assertEqual(list(self.runs.glob(".world-clone-*")), [])

    def test_clone_permissions_are_exact_without_chown(self):
        self.ensure()
        result = self.store.clone(PROFILE, self.runs / "writable", file_mode=0o666, directory_mode=0o777)
        root = Path(result["path"])
        self.assertEqual(stat.S_IMODE(root.stat().st_mode), 0o777)
        self.assertEqual(stat.S_IMODE((root / "region").stat().st_mode), 0o777)
        self.assertEqual(stat.S_IMODE((root / "level.dat").stat().st_mode), 0o666)

    def test_path_traversal_symlink_parent_and_template_destination_are_rejected(self):
        self.ensure()
        (self.root / "alias").symlink_to(self.runs, target_is_directory=True)
        for dest in [self.runs / ".." / "escape", self.root / "alias/world",
                     self.store.root / "overwrite"]:
            with self.subTest(dest=str(dest)), self.assertRaises(worlds.WorldTemplateError):
                self.store.clone(PROFILE, dest)

    def test_same_profile_concurrent_preparation_executes_callback_once(self):
        counter = []
        mutex = threading.Lock()
        def prepare(path):
            with mutex:
                counter.append(path)
            time.sleep(0.03)
            saved_world(path)
        with ThreadPoolExecutor(max_workers=4) as pool:
            results = list(pool.map(lambda _: self.store.ensure(PROFILE, prepare), range(4)))
        self.assertEqual(len(counter), 1)
        self.assertEqual(sum(not r["reused"] for r in results), 1)
        self.assertEqual(len({r["manifest_sha256"] for r in results}), 1)

    def test_resource_budget_failure_is_not_published(self):
        limited = worlds.TemplateStore(self.root / "limited", limits=worlds.Limits(max_total_bytes=64))
        with self.assertRaises(worlds.WorldTemplateError):
            limited.ensure(PROFILE, self.generate)
        self.assertEqual(list((limited.root / "templates").iterdir()), [])

    def test_cache_symlink_is_quarantined_without_following_target(self):
        outside = self.root / "outside"
        outside.mkdir()
        (outside / "keep").write_text("keep")
        (self.store.root / "templates" / worlds.profile_key(PROFILE)).symlink_to(outside, target_is_directory=True)
        self.ensure()
        self.assertEqual((outside / "keep").read_text(), "keep")
        self.assertTrue((self.store.root / "templates" / worlds.profile_key(PROFILE)).is_dir())


